def list_exercises(query: str = "", muscle_group: str = "", category: str = ""):
    items = EXERCISES
    if category:
        items = [e for e in items if e.get("category", "gym").lower() == category.lower()]
    if muscle_group:
        items = [e for e in items if e["muscle_group"].lower() == muscle_group.lower()]
    if query:
        q = query.lower()
        items = [e for e in items if q in e["name"].lower() or q in e["muscle_group"].lower()]
    return items


def get_exercise(eid: str):
    for e in EXERCISES:
        if e["id"] == eid:
            return e
    return None


def muscle_groups():
    seen = []
    for e in EXERCISES:
        if e["muscle_group"] not in seen:
            seen.append(e["muscle_group"])
    return seen


def categories():
    seen = []
    for e in EXERCISES:
        c = e.get("category", "gym")
        if c not in seen:
            seen.append(c)
    return [{"key": c, "label": CATEGORY_LABELS.get(c, c.title()), "count": sum(1 for e in EXERCISES if e.get("category", "gym") == c)} for c in seen]

